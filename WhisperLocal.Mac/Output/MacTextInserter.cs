using WhisperLocal.Config;
using WhisperLocal.Mac.Input;
using static WhisperLocal.Mac.Interop.MacNative;
using static WhisperLocal.Mac.Interop.ObjC;

namespace WhisperLocal.Mac.Output;

/// <summary>Inserts text into the frontmost app via the pasteboard + Cmd+V. Must run on the main thread.</summary>
internal sealed class MacTextInserter
{
    private const string StringType = "public.utf8-plain-text";
    private const ushort KeyCodeV = 9; // kVK_ANSI_V; Cmd shortcuts use the Latin layout, so this also works with Ukrainian input
    private const ushort KeyCodeZ = 6; // kVK_ANSI_Z

    // nspasteboard.org markers: clipboard managers neither show nor keep the dictated text
    private static readonly string[] MarkerTypes = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"];

    public async Task InsertAsync(string text, FrontmostApp? target, InsertConfig cfg)
    {
        var current = FrontmostApp.Capture();
        if (target != null && current.ProcessId != target.ProcessId)
            Log.Info($"Frontmost app changed during processing ({target.ProcessName} -> {current.ProcessName}), inserting into the current one");

        if (!AXIsProcessTrusted())
            Log.Warn("Accessibility permission is missing: the paste keystroke will be blocked. The text stays on the clipboard.");

        var saved = cfg.RestoreClipboard ? SnapshotPasteboard() : null;

        WithPool(() =>
        {
            var pb = Send(Class("NSPasteboard"), Sel("generalPasteboard"));
            Send(pb, Sel("clearContents"));
            Send(pb, Sel("setString:forType:"), Str(text), Str(StringType));
            foreach (var marker in MarkerTypes)
                Send(pb, Sel("setData:forType:"), Data([]), Str(marker));
        });

        await WaitForModifiersReleasedAsync();
        SendCmd(KeyCodeV);

        if (saved == null)
            return;

        // The target app reads the pasteboard asynchronously after Cmd+V
        await Task.Delay(cfg.RestoreDelayMs);
        try
        {
            RestorePasteboard(saved);
        }
        catch (Exception ex)
        {
            Log.Warn($"Failed to restore the clipboard: {ex.Message}");
        }
    }

    /// <summary>Undoes the last paste (Cmd+Z) and pastes <paramref name="text"/> instead.</summary>
    public async Task ReplaceLastAsync(string text, FrontmostApp? target, InsertConfig cfg)
    {
        await WaitForModifiersReleasedAsync();
        SendCmd(KeyCodeZ);
        // The app applies the undo before it reads the next keystroke, but give it a moment
        await Task.Delay(80);
        await InsertAsync(text, target, cfg);
    }

    /// <summary>Puts <paramref name="text"/> on the clipboard (where it stays, unlike a pasted dictation).</summary>
    public static void Copy(string text) => WithPool(() =>
    {
        var pb = Send(Class("NSPasteboard"), Sel("generalPasteboard"));
        Send(pb, Sel("clearContents"));
        Send(pb, Sel("setString:forType:"), Str(text), Str(StringType));
    });

    /// <summary>Copies every item and type currently on the general pasteboard.</summary>
    private static List<List<(string Type, byte[] Data)>>? SnapshotPasteboard()
    {
        try
        {
            return WithPool(() =>
            {
                var pb = Send(Class("NSPasteboard"), Sel("generalPasteboard"));
                var items = new List<List<(string, byte[])>>();
                foreach (var item in Items(Send(pb, Sel("pasteboardItems"))))
                {
                    var copy = new List<(string, byte[])>();
                    foreach (var type in Items(Send(item, Sel("types"))))
                    {
                        var data = Send(item, Sel("dataForType:"), type);
                        // Promised (lazily provided) data may be unavailable; skip it
                        if (data != IntPtr.Zero)
                            copy.Add((FromStr(type)!, FromData(data)));
                    }
                    items.Add(copy);
                }
                return items;
            });
        }
        catch (Exception ex)
        {
            Log.Warn($"Failed to read the clipboard: {ex.Message}");
            return null;
        }
    }

    private static void RestorePasteboard(List<List<(string Type, byte[] Data)>> saved) => WithPool(() =>
    {
        var pb = Send(Class("NSPasteboard"), Sel("generalPasteboard"));
        Send(pb, Sel("clearContents"));
        if (saved.Count == 0)
            return;

        var array = Send(Class("NSMutableArray"), Sel("array"));
        foreach (var entries in saved)
        {
            var item = New("NSPasteboardItem");
            foreach (var (type, data) in entries)
                Send(item, Sel("setData:forType:"), Data(data), Str(type));
            Send(array, Sel("addObject:"), item);
            Release(item);
        }
        Send(pb, Sel("writeObjects:"), array);
    });

    /// <summary>
    /// With a combination hotkey a modifier may still be held (e.g. Control released after Command),
    /// which would turn Cmd+V into Ctrl+Cmd+V. Wait briefly until all modifiers are up.
    /// </summary>
    private static async Task WaitForModifiersReleasedAsync()
    {
        const ulong modifiers = kCGEventFlagMaskShift | kCGEventFlagMaskControl | kCGEventFlagMaskAlternate
                                | kCGEventFlagMaskCommand | kCGEventFlagMaskSecondaryFn;
        var deadline = DateTime.UtcNow.AddMilliseconds(1500);
        while ((CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState) & modifiers) != 0)
        {
            if (DateTime.UtcNow > deadline)
            {
                Log.Warn("Modifier keys are still held, pasting anyway");
                return;
            }
            await Task.Delay(20);
        }
    }

    private static void SendCmd(ushort keyCode)
    {
        // A private source keeps the physical modifier state out of the posted events
        var source = CGEventSourceCreate(kCGEventSourceStatePrivate);
        foreach (var down in new[] { true, false })
        {
            var evt = CGEventCreateKeyboardEvent(source, keyCode, down);
            if (evt == IntPtr.Zero)
            {
                Log.Warn($"Cannot create the Cmd keyboard event (key {keyCode})");
                break;
            }
            CGEventSetFlags(evt, kCGEventFlagMaskCommand);
            CGEventSetIntegerValueField(evt, kCGEventSourceUserData, HotkeyTap.InjectedMarker);
            CGEventPost(kCGHIDEventTap, evt);
            CFRelease(evt);
        }
        if (source != IntPtr.Zero)
            CFRelease(source);
    }
}
